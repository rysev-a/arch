import { MEM_SIZE } from './isa';

/** Область на диске, которую интерфейс подписывает над сеткой памяти */
export interface DiskRegion {
  name: string;
  from: number;
  length: number;
}

export interface CheckResult {
  ok: boolean;
  message: string;
}

export interface AsmTask {
  id: string;
  title: string;
  /** Условие: что лежит на диске и что нужно сделать */
  text: string;
  /** Подсказка (по кнопке) */
  hint: string;
  /** Заготовка программы */
  starter: string;
  /** Эталонное решение — для тестов и кнопки «Показать решение» */
  solution: string;
  /** Исходное содержимое диска */
  disk: Uint8Array;
  regions: readonly DiskRegion[];
  /** Какой должна быть память после остановки */
  expected: Uint8Array;
  /** Разбор итога: что именно не так */
  check(mem: Uint8Array): CheckResult;
}

const bytes = (s: string): number[] => [...s].map((c) => c.charCodeAt(0));

/** Собирает диск: адрес → байты (число или строка) */
function makeDisk(parts: Record<number, number | number[] | string>): Uint8Array {
  const d = new Uint8Array(MEM_SIZE);
  for (const [addr, v] of Object.entries(parts)) {
    const list = typeof v === 'number' ? [v] : typeof v === 'string' ? bytes(v) : v;
    list.forEach((b, i) => (d[Number(addr) + i] = b));
  }
  return d;
}

export const hex = (n: number) => `0x${n.toString(16).toUpperCase().padStart(2, '0')}`;

const show = (b: number) => (b >= 32 && b < 127 ? `${hex(b)} «${String.fromCharCode(b)}»` : hex(b));

/** Сравнение памяти с ожидаемой: первое расхождение понятным языком */
function compare(mem: Uint8Array, expected: Uint8Array): CheckResult {
  const diffs: number[] = [];
  for (let i = 0; i < MEM_SIZE; i++) if (mem[i] !== expected[i]) diffs.push(i);
  if (diffs.length === 0)
    return { ok: true, message: 'Диск совпал с ожидаемым — задание выполнено!' };
  const first = diffs[0];
  const more =
    diffs.length > 1
      ? ` (и ещё ${diffs.length - 1} ${diffs.length === 2 ? 'байт' : 'байт(а)'})`
      : '';
  return {
    ok: false,
    message: `Адрес ${hex(first)}: ожидалось ${show(expected[first])}, а лежит ${show(mem[first])}${more}`,
  };
}

function task(
  t: Omit<AsmTask, 'expected' | 'check'> & { result: Record<number, number | number[] | string> },
): AsmTask {
  const expected = new Uint8Array(t.disk);
  const { result, ...rest } = t;
  for (const [addr, v] of Object.entries(result)) {
    const list = typeof v === 'number' ? [v] : typeof v === 'string' ? bytes(v) : v;
    list.forEach((b, i) => (expected[Number(addr) + i] = b));
  }
  return { ...rest, expected, check: (mem) => compare(mem, expected) };
}


import { Bit, GateType, InputId } from './circuit.model';

/** Один шаг сценария для последовательностных схем (защёлки) */
export interface ExerciseStep {
  /** требуемое состояние тумблеров (перечисляются все активные входы упражнения) */
  inputs: Partial<Record<InputId, Bit>>;
  /** ожидаемые значения выходов; выход, которого здесь нет, на этом шаге не проверяется */
  expect: Partial<Record<string, Bit>>;
  /** пояснение шага */
  text: string;
  /** Сколько импульсов такта нужно подать, чтобы дойти до этого шага (по умолчанию — один) */
  pulses?: number;
}

/** Группа узлов упражнения, объединённая в один порт заданного типа интерфейса */
export interface PortDecl {
  name: string;
  /** Имя типа из interfaces.ts */
  type: string;
  /** Узлы упражнения (входы A–F или имена выходов) по порядку бит типа: старший — первый */
  nodes: readonly string[];
}

export interface Exercise {
  id: string;
  title: string;
  /** Текст задания для студента */
  task: string;
  /** Какие входы размещены на доске (физические узлы A/B/C) */
  inputs: readonly InputId[];
  /** Подписи входов на доске (по порядку inputs); по умолчанию — сами id */
  labels?: readonly string[];
  /** Имена выходов на доске */
  outputs: readonly string[];
  /** Целевая таблица: строка = 2^inputs.length, в строке — по значению на каждый выход */
  target: readonly (readonly Bit[])[];
  /** Какие элементы доступны в палитре (пустой список — нужны только провода) */
  allowed: readonly GateType[];
  /** 'table' — сверка с таблицей истинности; 'steps' — пошаговый сценарий (последовательностная схема) */
  mode?: 'table' | 'steps';
  steps?: readonly ExerciseStep[];
  /**
   * Как собирается решение: из вентилей (по умолчанию) или из готовых блоков, соединённых шинами.
   * В режиме блоков вход и выход упражнения — порты `ports`, а палитра — блоки `blocks`.
   */
  kind?: 'gates' | 'blocks';
  /** Интерфейс упражнения: узлы, сгруппированные в типизированные порты */
  ports?: readonly PortDecl[];
  /** Решённое упражнение становится блоком с таким id (схема ученика сохраняется) */
  block?: { id: string; title: string };
  /** Какие блоки доступны в палитре (для kind = 'blocks') */
  blocks?: readonly string[];
  /** Какой из входов — тактовый: рядом с доской появляются кнопка «Такт» и автогенератор */
  clock?: InputId;
  /**
   * Шаги сценария достигаются импульсами такта (кнопка «Такт»): между шагами такт возвращается в 0,
   * новые данные выставляются при CLK = 0, а затем такт даёт фронт. Без флага такт — обычный тумблер.
   */
  ticks?: boolean;
  hint: string;
  /** Формула для заголовка после победы */
  formula: string;
  /** Объяснение после победы */
  success: string;
}

/**
 * Целевая таблица по функции: на вход — биты входов упражнения (первый вход — старший),
 * на выходе — значения выходов. Нужна для больших таблиц (до 64 строк), чтобы не писать их вручную.
 */
export function tableOf(inputCount: number, fn: (bits: Bit[]) => Bit[]): Bit[][] {
  return Array.from({ length: 2 ** inputCount }, (_, row) =>
    fn(Array.from({ length: inputCount }, (_, i) => ((row >> (inputCount - 1 - i)) & 1) as Bit)),
  );
}


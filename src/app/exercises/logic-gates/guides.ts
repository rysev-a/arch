import { Bit, GateType, InputId, PinKind } from './circuit.model';
import { BusEnd } from './blocks';

/**
 * Пошаговые разборы для «режима авто»: что делать на доске и объяснение к каждому шагу.
 * Разбор — это одновременно учебник (текст) и тренажёр (действия выполняются на настоящей доске).
 */
export type GuideAction =
  /** поставить элемент; name — имя для ссылок в проводах, at — центр элемента на доске */
  | { place: GateType; name: string; at: { x: number; y: number } }
  /** провести провод: из выхода источника (вход-тумблер или элемент по имени) на вход приёмника */
  | { wire: { from: string; to: string; pin: PinKind } }
  /** поставить блок (упражнения «из блоков»); x, y — левый верхний угол */
  | { block: { id: string; blockId: string; x: number; y: number } }
  /** протянуть шину между портами блоков (node '$' — порты самого упражнения) */
  | { bus: { id: string; from: BusEnd; to: BusEnd } }
  /** выставить тумблеры */
  | { set: Partial<Record<InputId, Bit>> }
  /** импульсы такта (true — один) */
  | { pulse: number | true };

export interface GuideStep {
  title: string;
  /** Объяснение. Абзацы разделены пустой строкой; **так** выделяется важное. */
  text: string;
  /** Что шаг делает на доске (может быть несколько действий) */
  do?: readonly GuideAction[];
  /** Номер шага сценария упражнения (режим шагов), который выполняет этот шаг */
  completes?: number;
}

export interface Guide {
  steps: readonly GuideStep[];
}

const place = (type: GateType, name: string, x: number, y: number): GuideAction => ({
  place: type,
  name,
  at: { x, y },
});
const wire = (from: string, to: string, pin: PinKind): GuideAction => ({
  wire: { from, to, pin },
});


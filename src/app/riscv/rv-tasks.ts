import { RvView } from './rv-machine';
import { RAM_SIZE } from './rv-asm';

export interface CheckResult {
  ok: boolean;
  message: string;
}

export interface RvTask {
  id: string;
  title: string;
  text: string;
  hint: string;
  /** Заготовка программы */
  starter: string;
  /** Эталонное решение — для тестов и кнопки «Показать решение» */
  solution: string;
  /** Данные задания: ассемблерный текст секции .data; дописывается к программе и не редактируется */
  data: string;
  /** В каком положении стоят переключатели */
  switches?: number;
  /** Что считается «зависанием» */
  maxSteps?: number;
  check(v: RvView, sym: Record<string, number>): CheckResult;
}

const ok = (message: string): CheckResult => ({ ok: true, message });
const bad = (message: string): CheckResult => ({ ok: false, message });

const bin8 = (n: number) => `0b${(n & 0xff).toString(2).padStart(8, '0')}`;
const word = (mem: Uint8Array, a: number): number =>
  mem[a] | (mem[a + 1] << 8) | (mem[a + 2] << 16) | (mem[a + 3] << 24);
const cstr = (mem: Uint8Array, a: number): string => {
  let s = '';
  while (a < mem.length && mem[a] !== 0) s += String.fromCharCode(mem[a++]);
  return s;
};

/** Полный текст программы: то, что написал ученик, плюс данные задания */
export function fullSource(user: string, task: RvTask): string {
  return `${user}\n.data\n${task.data}\n`;
}

